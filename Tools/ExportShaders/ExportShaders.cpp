// Compiles every vertex, fragment and compute shader of one namespace of a shader assembly and writes the results as a C++ header
// for the Helix.RHI tests: GLSL 3.30 and GLSL ES 3.00 (4.30 and 3.10 for compute shaders), Direct3D bytecode and the GLSL
// binding table of each shader. Assemblies it references (the shader library, includes) are loaded from its directory.
//
// usage: helix_export_shaders <assembly.dll> <namespace> <output.h>

#include <Helix/Core/Strings/Format.h>
#include <Helix/ShaderCompiler/Assembly/AssemblyResolver.h>
#include <Helix/ShaderCompiler/Backends/Dxbc.h>
#include <Helix/ShaderCompiler/Backends/Glsl.h>
#include <Helix/ShaderCompiler/Frontend/Frontend.h>

#include <cstdio>

using namespace helix;
using namespace helix::shadercompiler;

namespace
{
    bool ReadFile(const char* path, Array<u8>& out)
    {
        std::FILE* f = std::fopen(path, "rb");
        if (!f)
            return false;
        u8 buffer[65536];
        for (usize n; (n = std::fread(buffer, 1, sizeof(buffer), f)) > 0;)
            out.Append(buffer, n);
        std::fclose(f);
        return true;
    }

    // A C string literal, one source line per literal so no compiler limit is reached.
    void AppendLiteral(String& out, StringView text)
    {
        out.Append("\n        \"");
        for (char c : text)
        {
            if (c == '\n')
                out.Append("\\n\"\n        \"");
            else if (c == '"' || c == '\\')
                out.Append('\\').Append(c);
            else
                out.Append(c);
        }
        out.Append("\"");
    }

    bool HasAttribute(const Assembly& a, u32 method, StringView name)
    {
        Array<CustomAttribute> attributes;
        a.Attributes(Token(Table::MethodDef, method), attributes);
        for (const CustomAttribute& c : attributes)
            if (c.typeName == name)
                return true;
        return false;
    }
}

int main(int argc, char** argv)
{
    if (argc != 4)
    {
        std::fprintf(stderr, "usage: helix_export_shaders <assembly.dll> <namespace> <output.h>\n");
        return 2;
    }
    Array<u8> image;
    Assembly a;
    if (!ReadFile(argv[1], image) || !a.Load(Span<const u8>(image.Data(), image.Size())))
    {
        std::fprintf(stderr, "cannot load %s: %s\n", argv[1], a.Error().CStr());
        return 1;
    }
    StringView path(argv[1]);
    usize slash = 0;
    for (usize i = 0; i < path.Size(); i++)
        if (path[i] == '/' || path[i] == '\\')
            slash = i;
    AssemblyResolver resolver;
    resolver.AddDirectory(slash ? path.Substr(0, slash) : StringView("."));
    String missing;
    if (!resolver.LoadReferences(a, missing))
        std::fprintf(stderr, "warning: %s references %s, which is not next to it\n", argv[1], missing.CStr());
    TranslateOptions options;
    options.references = resolver.References();

    String out;
    out.Append("// Generated by helix_export_shaders of Helix.ShaderCompiler from the C# shaders in its Tests/Shaders/Rhi. Do not edit:\n"
               "// change the C# source there, build the export_rhi_shaders target and copy its output over this file.\n"
               "#pragma once\n\n#include <Support/CompiledShader.h>\n\nnamespace helix::rhi::testing\n{\n");
    u32 count = 0;
    for (u32 row = 1; row <= a.RowCount(Table::TypeDef); row++)
    {
        TypeDefInfo type = a.TypeDef(row);
        if (type.nameSpace != StringView(argv[2]))
            continue;
        for (u32 method = type.methodBegin; method < type.methodEnd; method++)
        {
            bool vertex = HasAttribute(a, method, "VertexShaderAttribute"), compute = HasAttribute(a, method, "ComputeShaderAttribute");
            if (!vertex && !compute && !HasAttribute(a, method, "FragmentShaderAttribute"))
                continue;
            Stage stage = vertex ? Stage::Vertex : compute ? Stage::Compute : Stage::Fragment;
            Module module;
            GlslShader glsl, essl;
            DxbcShader dxbc;
            String error;
            // Compute shaders exist from GLSL 4.30 and GLSL ES 3.10, bindless buffers from GLSL 4.30 and bindless textures from
            // 4.50 with ARB_bindless_texture; GLES has no bindless resources, so those shaders get no ES source.
            bool translated = TranslateEntryPoint(a, method, stage, module, error, options);
            BindlessUse bindless = translated ? FindBindless(module) : BindlessUse();
            GlslTarget desktop = bindless.textures ? GlslTarget::Glsl450 : compute || bindless.buffers ? GlslTarget::Glsl430 : GlslTarget::Glsl330;
            bool mobile = !bindless.textures && !bindless.buffers;
            if (!translated || !EmitGlsl(module, desktop, glsl, error) ||
                (mobile && !EmitGlsl(module, compute ? GlslTarget::Essl310 : GlslTarget::Essl300, essl, error)) ||
                !EmitDxbc(module, dxbc, error))
            {
                std::fprintf(stderr, "%s.%s: %s\n", String(type.name).CStr(), String(a.Method(method).name).CStr(), error.CStr());
                return 1;
            }
            String name = Format("k{}{}", type.name, a.Method(method).name);
            FormatAppend(out, "    inline const unsigned char {}Dxbc[] = {{", name);
            for (usize i = 0; i < dxbc.bytes.Size(); i++)
                FormatAppend(out, "{}{},", i % 32 == 0 ? "\n        " : "", u32(dxbc.bytes[i]));
            out.Append("\n    };\n");
            if (!glsl.bindings.Empty())
            {
                FormatAppend(out, "    inline const ShaderBinding {}Bindings[] = {{", name);
                for (const GlslBinding& b : glsl.bindings)
                    FormatAppend(out, "{{\"{}\", BindingKind::{}, {}}}, ", b.name, b.kind == GlobalKind::Uniform ? "UniformBuffer" : "Texture", b.slot);
                out.Append("};\n");
            }
            FormatAppend(out, "    inline const CompiledShader {} = {{\n        ShaderStage::{},", name, vertex ? "Vertex" : compute ? "Compute" : "Fragment");
            AppendLiteral(out, glsl.source);
            out.Append(",");
            AppendLiteral(out, essl.source);
            FormatAppend(out, ",\n        {}Dxbc, sizeof({}Dxbc), ", name, name);
            if (glsl.bindings.Empty())
                out.Append("nullptr, 0,\n    };\n\n");
            else
                FormatAppend(out, "{}Bindings, {},\n    }};\n\n", name, u32(glsl.bindings.Size()));
            count++;
        }
    }
    out.Append("}\n");
    if (!count)
    {
        std::fprintf(stderr, "no shaders in namespace %s\n", argv[2]);
        return 1;
    }
    std::FILE* f = std::fopen(argv[3], "wb");
    if (!f || std::fwrite(out.Data(), 1, out.Size(), f) != out.Size())
    {
        std::fprintf(stderr, "cannot write %s\n", argv[3]);
        return 1;
    }
    std::fclose(f);
    std::printf("%u shaders written to %s\n", count, argv[3]);
    return 0;
}
